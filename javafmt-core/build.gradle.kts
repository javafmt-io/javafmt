description = "Core formatting engine for javafmt."

// The formatter's version has to be readable at runtime: FileFormatCache keys its entries on it
// so a javafmt upgrade invalidates hashes produced by the previous release. Reading it from the
// JAR manifest instead would return null from a classes directory, from tests, and from the
// GraalVM native image — exactly where the cache is used most.
val generateVersionClass = tasks.register("generateVersionClass") {
    val version = providers.provider { project.version.toString() }
    val outputDir = layout.buildDirectory.dir("generated/sources/version/java")
    inputs.property("version", version)
    outputs.dir(outputDir)
    doLast {
        val packageDir = outputDir.get().asFile.resolve("io/javafmt")
        packageDir.mkdirs()
        packageDir.resolve("JavafmtVersion.java").writeText(
            """
            package io.javafmt;

            /** The released version of javafmt. Generated by the build from the project version. */
            public final class JavafmtVersion {

                /** The version string, e.g. {@code 0.1.0} or {@code 0.1.1-SNAPSHOT}. Never blank. */
                public static final String VERSION = "${version.get()}";

                private JavafmtVersion() {}
            }
            """.trimIndent() + "\n",
        )
    }
}

sourceSets["main"].java.srcDir(generateVersionClass)

// Where the corpus gate reads java.base from. Resolved from the same toolchain the module compiles
// against, so the corpus is always the JDK javafmt claims to support and the run stays offline.
val corpusSourceZip = javaToolchains.launcherFor(java.toolchain).map {
    it.metadata.installationPath.file("lib/src.zip").asFile.absolutePath
}

testing {
    suites {
        // The corpus gate formats the JDK's own java.base sources — read out of the toolchain's
        // lib/src.zip, so nothing is downloaded and nothing is checked in — and holds the result
        // against a recorded baseline. It is the test that catches a renderer dropping tokens, a
        // lint rule hanging, or output that stops being idempotent, none of which a hand-written
        // fixture would have found.
        register<JvmTestSuite>("corpusTest") {
            useJUnitJupiter(libs.versions.junit)
            dependencies {
                implementation(project())
                implementation(libs.assertj.core)
                compileOnly(libs.jspecify)
            }
            targets {
                all {
                    testTask.configure {
                        shouldRunAfter(tasks.named("test"))
                        maxHeapSize = "2g"
                        systemProperty("javafmt.corpus.srczip", corpusSourceZip.get())
                        // The summary table is the deliverable: a reader of the build log has to be
                        // able to see the counts move without opening the HTML report.
                        testLogging.showStandardStreams = true
                    }
                }
            }
        }

