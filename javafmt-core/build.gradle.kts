// JMH's bundled ASM 9.0 cannot read Java 25 class files, which breaks any bytecode-rewriting
// agent inside a benchmark fork (jvm-hotpath detects this and warns). Forcing a current ASM on
// the jmh classpath is the fix the agent's docs prescribe.
dependencies {
    jmh(libs.asm)
    // Benchmark-only baseline for GjfComparisonBenchmark; never on any published classpath.
    jmh(libs.google.java.format)
}

// Benchmark results always land as JSON so a regression check — or an LLM reading the run —
// works off numbers rather than scraped console output.
jmh {
    resultFormat.set("JSON")
    resultsFile.set(layout.buildDirectory.file("reports/jmh/results.json"))
    // RealWorldCorpus benchmarks against javafmt's own sources — real production Java, no download
    // step, no third-party license to carry. Reading happens in @Setup, never in a measured method.
    jvmArgsAppend.add("-Djavafmt.corpus=${layout.projectDirectory.dir("src/main/java").asFile.absolutePath}")
    // google-java-format drives javac through internal APIs, so GjfComparisonBenchmark cannot even
    // load without these. javafmt itself needs none of them — that is the distribution tradeoff
    // JavaParser's javadoc records — but the benchmark JVM hosts both formatters.
    jvmArgsAppend.addAll(
        listOf("api", "code", "comp", "file", "main", "parser", "tree", "util")
            .map { "--add-exports=jdk.compiler/com.sun.tools.javac.$it=ALL-UNNAMED" },
    )
    if (project.hasProperty("jmhInclude")) {
        includes.add(project.property("jmhInclude") as String)
    }
    if (providers.gradleProperty("jmhProof").isPresent) {
        fork.set(3)
        warmupIterations.set(5)
        iterations.set(10)
    }
}

// Profilers are opt-in: instrumentation distorts the timings the benchmarks exist to measure,
// so a plain `gradle :javafmt-core:jmh` never attaches one.
//
//   gradle :javafmt-core:jmh -PjmhProfile=gc       allocation rate and GC pressure   (no install)
//   gradle :javafmt-core:jmh -PjmhProfile=stack    sampled hot methods               (no install)
//   gradle :javafmt-core:jmh -PjmhProfile=jfr      JFR recording per fork            (no install)
//   gradle :javafmt-core:jmh -PjmhProfile=hotpath  per-line execution counts as JSON (no install)
//   gradle :javafmt-core:jmh -PjmhProfile=async    flamegraphs (brew install async-profiler)
//
// Scope any run with -PjmhInclude=JavafmtFormatBenchmark.*
val jmhProfile = providers.gradleProperty("jmhProfile").orNull
if (jmhProfile != null) {
    val hotpathOutput = layout.buildDirectory.file("reports/jmh/execution-report.json").get().asFile.absolutePath
    val agentJar = configurations.named("jvmHotpathAgent").map { it.files.first { f -> f.name.startsWith("jvm-hotpath-agent") }.absolutePath }
    val sourceDir = layout.projectDirectory.dir("src/main/java").asFile.absolutePath
    jmh {
        // Profiling runs trade statistical confidence for turnaround; full fidelity is the
        // unprofiled run's job.
        warmupIterations.set(1)
        iterations.set(3)
        fork.set(1)
        when (jmhProfile) {
            "gc" -> profilers.add("gc")
            "stack" -> profilers.add("stack")
            "jfr" -> profilers.add("jfr")
            "async" -> profilers.add(
                "async:libPath=/opt/homebrew/opt/async-profiler/lib/libasyncProfiler.dylib;output=flamegraph,collapsed;" +
                    "dir=${layout.buildDirectory.dir("jmh-async").get().asFile.absolutePath}",
            )
            // append/flushInterval are required because JMH runs each benchmark in its own fork:
            // without them each fork would overwrite the previous fork's counts, or lose them at exit.
            "hotpath" -> jvmArgsAppend.add(
                agentJar.map { "-javaagent:$it=packages=io.javafmt,sourcepath=$sourceDir,append=true,flushInterval=1,output=$hotpathOutput" },
            )
            else -> throw GradleException("unknown -PjmhProfile=$jmhProfile (expected gc, stack, jfr, hotpath or async)")
        }
    }
}
