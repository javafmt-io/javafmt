    testImplementation(testFixtures(project(":javafmt-core")))
    testRuntimeOnly(libs.junit.platform.launcher)
}

// The version gate needs the plugin's own version at runtime: a plugin that demands a newer
// binary than the one released beside it never formats anything. Generated rather than read from
// the JAR manifest, which returns null from a classes directory and from tests. Mirrors
// javafmt-core's JavafmtVersion; the two cannot share a class because this module deliberately
// does not depend on javafmt-core.
val generatePluginVersionClass by tasks.registering {
    val pluginVersion = providers.provider { project.version.toString() }
    val outputDir = layout.buildDirectory.dir("generated/sources/version/java")
    inputs.property("version", pluginVersion)
    outputs.dir(outputDir)
    doLast {
        val packageDir = outputDir.get().asFile.resolve("io/javafmt/intellij")
        packageDir.mkdirs()
        packageDir.resolve("JavafmtPluginVersion.java").writeText(
            """
            package io.javafmt.intellij;

            /** The version of the javafmt IntelliJ plugin. Generated by the build from the axion project version. */
            public final class JavafmtPluginVersion {

                /** The version string, e.g. {@code 0.1.0} or {@code 0.1.1-SNAPSHOT}. Never blank. */
                public static final String VERSION = "${pluginVersion.get()}";

                private JavafmtPluginVersion() {}
            }
            """.trimIndent() + "\n",
        )
    }
}

sourceSets["main"].java.srcDir(generatePluginVersionClass)

tasks.named<JavaCompile>("compileJava") {
    options.release.set(21)
}

tasks.named<Test>("test") {
    useJUnitPlatform()
    // The version gate is derived from the plugin's own version, so the test that pins the two
    // together needs the version the build stamped, independently of the generated source.
    systemProperty("javafmt.buildVersion", project.version.toString())
    javaLauncher.set(javaToolchains.launcherFor {
        languageVersion.set(JavaLanguageVersion.of(25))
    })
}

